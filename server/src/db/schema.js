const path = require("path");
require("dotenv").config();
require("dotenv").config({ path: path.join(__dirname, "../../.env") });
const { Pool } = require("pg");

const connectionString =
  process.env.SUPABASE_DB_URL || process.env.DATABASE_URL;

if (!connectionString) {
  throw new Error(
    "Missing SUPABASE_DB_URL or DATABASE_URL environment variable",
  );
}

const pool = new Pool({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

function normalizeSql(sql) {
  let text = sql;

  text = text.replace(/datetime\('now'\)/gi, "CURRENT_TIMESTAMP");
  text = text.replace(/date\('now'\)/gi, "CURRENT_DATE");
  text = text.replace(
    /date\('now',\s*'start of month'\)/gi,
    "DATE_TRUNC('month', CURRENT_DATE)::date",
  );
  text = text.replace(
    /date\('now',\s*'-1 day'\)/gi,
    "(CURRENT_DATE - INTERVAL '1 day')::date",
  );
  text = text.replace(
    /date\('now',\s*'\+1 day'\)/gi,
    "(CURRENT_DATE + INTERVAL '1 day')::date",
  );
  text = text.replace(
    /date\('now',\s*\?\s*\|\|\s*' days'\)/gi,
    "CURRENT_DATE + (?::integer * INTERVAL '1 day')",
  );
  text = text.replace(/julianday\('now'\)/gi, "CURRENT_TIMESTAMP");
  text = text.replace(
    /julianday\('now'\)\s*-\s*julianday\(([^)]+)\)/gi,
    "EXTRACT(EPOCH FROM (CURRENT_TIMESTAMP - $1)) / 86400.0",
  );
  text = text.replace(
    /julianday\(([^)]+)\)/gi,
    "EXTRACT(EPOCH FROM $1) / 86400.0",
  );
  text = text.replace(/date\(([^)]+)\)/gi, "DATE($1)");

  const placeholderCount = (text.match(/\?/g) || []).length;
  let index = 1;
  text = text.replace(/\?/g, () => `$${index++}`);

  text = text.trim().replace(/;+$/, "");
  if (/^\s*INSERT\b/i.test(text) && !/\bRETURNING\b/i.test(text)) {
    text = `${text} RETURNING id`;
  }

  return { text, placeholderCount };
}

const db = {
  async execute(queryOrObject) {
    const { sql, args = [] } =
      typeof queryOrObject === "string"
        ? { sql: queryOrObject, args: [] }
        : queryOrObject;

    const { text } = normalizeSql(sql);
    const result = await pool.query(text, args);

    return {
      rows: result.rows || [],
      lastInsertRowid: result.rows?.[0]?.id ?? null,
    };
  },

  async batch(statements) {
    const conn = await pool.connect();
    try {
      await conn.query("BEGIN");
      const results = [];
      for (const statement of statements) {
        const { text } = normalizeSql(statement.sql);
        const result = await conn.query(text, statement.args || []);
        results.push({
          rows: result.rows || [],
          lastInsertRowid: result.rows?.[0]?.id ?? null,
        });
      }
      await conn.query("COMMIT");
      return results;
    } catch (error) {
      await conn.query("ROLLBACK");
      throw error;
    } finally {
      conn.release();
    }
  },
};

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE,
    role TEXT NOT NULL CHECK(role IN ('cairo_staff','kano_staff','abuja_staff','admin')),
    office TEXT NOT NULL CHECK(office IN ('Cairo','Kano','Abuja')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    last_login TIMESTAMPTZ
  );

  CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT,
    whatsapp TEXT,
    city TEXT,
    type TEXT DEFAULT 'Regular' CHECK(type IN ('Regular','VIP','Frequent','New','Dormant')),
    status TEXT DEFAULT 'Active' CHECK(status IN ('Active','Dormant','Blocked')),
    balance NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    created_by INTEGER REFERENCES users(id)
  );

  CREATE TABLE IF NOT EXISTS sacks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sack_number TEXT UNIQUE NOT NULL,
    destination TEXT NOT NULL CHECK(destination IN ('Kano','Abuja','Lagos')),
    flight_batch TEXT,
    status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','closed','shipped','arrived','cancelled')),
    capacity INTEGER DEFAULT 50,
    created_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    shipped_at TIMESTAMPTZ,
    arrived_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS parcels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_id TEXT UNIQUE NOT NULL,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    receiver_name TEXT NOT NULL,
    receiver_phone TEXT NOT NULL,
    destination TEXT NOT NULL CHECK(destination IN ('Kano','Abuja','Lagos')),
    parcel_type TEXT NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    weight NUMERIC NOT NULL,
    declared_value NUMERIC DEFAULT 0,
    description TEXT,
    notes TEXT,
    total_amount NUMERIC NOT NULL DEFAULT 0,
    amount_paid NUMERIC NOT NULL DEFAULT 0,
    balance NUMERIC GENERATED ALWAYS AS (total_amount - amount_paid) STORED,
    payment_method TEXT DEFAULT 'Cash',
    status TEXT NOT NULL DEFAULT 'received_cairo' CHECK(status IN ('received_cairo','packed','shipped','arrived_destination','out_for_delivery','delivered','hold','returned')),
    sack_id INTEGER REFERENCES sacks(id),
    collector_name TEXT,
    scale_photo_url TEXT,
    created_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by INTEGER REFERENCES users(id),
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS parcel_photos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id INTEGER NOT NULL REFERENCES parcels(id),
    file_url TEXT NOT NULL,
    file_type TEXT DEFAULT 'item_photo',
    uploaded_by INTEGER REFERENCES users(id),
    uploaded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    parcel_id INTEGER REFERENCES parcels(id),
    amount NUMERIC NOT NULL,
    payment_method TEXT DEFAULT 'Cash' CHECK(payment_method IN ('Cash','Bank Transfer','Mobile Money','Other')),
    type TEXT NOT NULL DEFAULT 'payment' CHECK(type IN ('payment','expense','balance_recorded')),
    notes TEXT,
    recorded_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS audit_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action TEXT NOT NULL,
    entity_type TEXT,
    entity_id INTEGER,
    user_id INTEGER REFERENCES users(id),
    details TEXT,
    ip_address TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS tracking_timeline (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id INTEGER NOT NULL REFERENCES parcels(id),
    status TEXT NOT NULL,
    note TEXT,
    office TEXT,
    updated_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  );
`;

async function initDB() {
  const statements = SCHEMA.split(";")
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
  for (const sql of statements) {
    await db.execute(sql + ";");
  }
  console.log("✅ Database schema initialized");
}

module.exports = { db, initDB };
